/* ============================================================
 * modes.js —— 呈现模式
 * ============================================================
 * 四种呈现模式：纯图 / 图文 / 海报 / 肖像。
 *
 * 为什么要分模式而不是只给一个开关：
 * 「要不要写字」与「画面里有什么」是两个独立决定。
 * 纯图模式要明确禁止文字（不然模型爱自己加字），
 * 图文模式要让文字参与构图（不然主题原文就白给了）。
 * 合成一个开关的结果是两头都不讨好。
 *
 * 模式只影响两件事：负面词，以及主题原文要不要进画面。
 * 它**不碰身份层** —— 换了模式，她还是那个人。
 * ============================================================ */
if (typeof module !== "undefined" && module.exports) {
  var _M = require("./data-core.js");
  var MODES = _M.MODES;
}

/* 注意：neg 的定义与 data-core.js 的 RENDER_MODES 保持一致。
   两处都写是为了让数据层可自解释 —— 但真源在 RENDER_MODES，
   下面的 MODES 是它的可执行副本，改一处必须改两处，
   所以 check_album 会断言两者逐条一致。 */
MODES.push(
{ k:"plain", zh:"纯图", order:1, isDefault:true,
  desc:"主题只决定画面内容，不生成任何文字。最常用",
  neg:["文字","字母","汉字","标点符号","水印","签名","logo","字幕","书法"],
  useWhen:"配图、封面、任何不该出现字的地方" },

{ k:"graphic", zh:"图文", order:2,
  desc:"保留主题原文，让文字参与构图。适合金句、海报、社交媒体配图",
  neg:["拼贴错位","字形畸变","乱码","多段无关文字"],
  useWhen:"金句卡片、语录图、带文案的配图" },

{ k:"poster", zh:"海报", order:3,
  desc:"主题原文成为主体，图像退为背景。留白与字级关系由版式决定",
  neg:["拥挤","重叠的文字","文字贴边","多色文字"],
  useWhen:"活动海报、宣传物料" },

{ k:"portrait", zh:"肖像", order:4,
  desc:"只有人，没有场景与道具。最省事也最不容易出错",
  neg:["道具","复杂背景","场景元素","文字"],
  useWhen:"头像、证件照式头像、只要脸" }
);