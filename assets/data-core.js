/* ============================================================
 * data-core.js —— 美人画册 · 全局容器与契约
 * ============================================================
 * 本库是什么：把「一个完整可复现的人物配方」压成一个三位编号，
 * 让人能像记住电话号码一样记住一个形象。
 *
 * 与「美人画册 提示词库」的分工（两者是同品牌下的两层，独立、不互相 require）：
 *   提示词库   零件层。七面解构、算子变形、冲突裁决。
 *              回答「这个人怎么拼出来的」。
 *   美人画册   成品册。编号 = 完整配方，主题 = 换什么内容。
 *              回答「我记住的 041 号，配这个主题怎么出图」。
 *
 * ------------------------------------------------------------
 * 本库的三条设计决定：
 *
 * ① **编号即入口**。
 *    零件层的编码只解决「找到条目」，不解决「记不住但要能复现」。
 *    用户记不住「冷调白皙 + 深眼窝 + 长颈」，但他记得住 041。
 *    编号是给记忆用的，不是给数据库用的 —— 所以它必须短、必须稳定、
 *    必须能在任何入口被敲出来。本库的所有入口都吃裸编号。
 *
 * ② **编号管画风、主题管内容**（正交两轴）。这是本库最要紧的一条：
 *    固定 041 号 + 换十个主题 = 十张风格一致、内容不同的图。
 *    固定主题 + 换编号 = 试不同画风。
 *    本库把这条轴翻译成人物语言：
 *      编号 → 骨相/肤质/眼目/形体/发型/气质（**这个人是谁，不变**）
 *      主题 → 妆造/场景/叙事（**画什么，随主题变**）
 *    为什么要这样切：妆造与场景是「时代与处境」的产物，
 *    骨相与气质是「这个人」的产物。前者随主题变，后者不该变 ——
 *    变了就不是同一个人了，而那正是「画册」要保证的事。
 *
 * ③ **参考图只借画法不借内容**。
 *    直接丢参考图，模型会把人物、动作、背景一起抄过来。
 *    本库在数据层就把「画法」与「内容」分开存放，
 *    提示词正文里先给画法（编号部分），再给内容（主题部分），
 *    两者用显式分隔，模型更容易只抓前者。
 *
 * 沿用自 anime-prompt-library（同一作者的另一库）的三条：
 *
 * ④ **授权分级**（rights.js）：把「能不能商用」变成可查数据而非口头声明。
 * ⑤ **槽位声明式抽卡**（gacha.js）：库升级时抽卡逻辑不用改。
 * ⑥ **契约式断言**：测「成品长什么样」而不是「函数没报错」。
 * ============================================================ */

